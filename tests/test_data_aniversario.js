/* Testa os três campos sem usar navegador ou conexão com Supabase. */
const fs = require('fs');
const vm = require('vm');
const assert = require('assert');
const source = fs.readFileSync(require('path').join(__dirname, '../static/js/data_aniversario.js'), 'utf8');
const context = {window: {}, Date};
vm.createContext(context);
vm.runInContext(source, context);
const ui = context.window.ClasseDataAniversario;
const els = () => ({nascimentoDia:{value:''}, nascimentoMes:{value:''}, nascimentoAno:{value:''}});
const resultado = x => JSON.parse(JSON.stringify(x));
let campos=els();
assert.deepStrictEqual(resultado(ui.obter(campos)), {data_nascimento:null, aniversario_dia_mes:null});
campos.nascimentoDia.value='29'; campos.nascimentoMes.value='2';
assert.deepStrictEqual(resultado(ui.obter(campos)), {data_nascimento:null, aniversario_dia_mes:'02-29'});
campos.nascimentoAno.value='2012';
assert.deepStrictEqual(resultado(ui.obter(campos)), {data_nascimento:'2012-02-29', aniversario_dia_mes:null});
campos.nascimentoAno.value='2011';
assert.throws(()=>ui.obter(campos), /inválidos/);
campos.nascimentoDia.value='31'; campos.nascimentoMes.value='4'; campos.nascimentoAno.value='';
assert.throws(()=>ui.obter(campos), /inválidos/);
campos.nascimentoMes.value='';
assert.throws(()=>ui.obter(campos), /preencha dia e mês/);
campos=els(); ui.preencher(campos,{data_nascimento:'2010-11-11'});
assert.strictEqual(campos.nascimentoAno.value, '2010');
assert.strictEqual(campos.nascimentoDia.value, '11');
assert.strictEqual(ui.formatar({data_nascimento:'2010-11-11'}), '11/11/2010');
ui.preencher(campos,{aniversario_dia_mes:'11-11'});
assert.strictEqual(campos.nascimentoAno.value, '');
assert.strictEqual(campos.nascimentoMes.value, '11');
assert.strictEqual(ui.formatar({aniversario_dia_mes:'11-11'}), '11/11 (ano não informado)');
console.log('Cadastro de aniversário: 11 casos aprovados');
